## Step-by-Step

1. **Turn the unit off** at the remote (and you can flip the breaker if you want to be thorough).
2. **Open the front panel** of the indoor head — it hinges upward and usually clicks when it's open.
3. **Slide out the filters** — the thin mesh screens behind the panel. Most units have two. Note how they sit so they go back the same way.
4. **Vacuum the loose dust** off with a brush attachment.
5. **Rinse with lukewarm water** — from the clean side through to the dirty side. For greasy buildup (kitchen-area units), a little mild dish soap helps. **No hot water, no harsh chemicals** — they can warp the mesh.
6. **Let them air-dry completely** — never reinstall a damp filter; it grows mold.
7. **Wipe the visible coil louvers** gently while the panel's open, if you can reach them.
8. **Reinsert the dry filters**, close the panel, and power back on.

That's it. Many premium units even have a "clean filter" reminder light that resets when you close the panel.

